"""Timing experiments.

1. Key generation and decryption cost vs modulus size (polynomial growth)
2. Factoring cost vs modulus size with Pollard's rho (exponential growth)

    python benchmarks/benchmark.py

Writes results/benchmark_results.md and results/rsa_timing.png.
"""

from __future__ import annotations

import statistics
import sys
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from rsa_group import attacks, rsa  # noqa: E402

RESULTS = ROOT / "results"


def time_it(fn, repeats: int) -> float:
    times = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        fn()
        times.append(time.perf_counter() - t0)
    return statistics.median(times)


def rsa_costs(sizes=(512, 1024, 2048), keygen_repeats=5, decrypt_repeats=20):
    rows = []
    for bits in sizes:
        keygen = time_it(lambda: rsa.generate_keypair(bits), keygen_repeats)
        pub, priv = rsa.generate_keypair(bits)
        c = rsa.encrypt(123456789, pub)
        enc = time_it(lambda: rsa.encrypt(123456789, pub), decrypt_repeats)
        dec = time_it(lambda: rsa.decrypt(c, priv), decrypt_repeats)
        crt = time_it(lambda: rsa.decrypt_crt(c, priv), decrypt_repeats)
        rows.append((bits, keygen, enc, dec, crt))
    return rows


def factoring_costs(sizes=(32, 40, 48, 56, 64, 72, 80), keys_per_size=5):
    rows = []
    for bits in sizes:
        times = []
        for _ in range(keys_per_size):
            pub, _ = rsa.generate_keypair(bits)
            t0 = time.perf_counter()
            attacks.pollard_rho(pub.n)
            times.append(time.perf_counter() - t0)
        rows.append((bits, statistics.median(times)))
    return rows


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    costs = rsa_costs()
    fact = factoring_costs()

    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    axes[0].plot([r[0] for r in costs], [r[3] * 1000 for r in costs], "o-", label="decrypt")
    axes[0].plot([r[0] for r in costs], [r[4] * 1000 for r in costs], "s-", label="decrypt (CRT)")
    axes[0].plot([r[0] for r in costs], [r[2] * 1000 for r in costs], "^-", label="encrypt (e = 65537)")
    axes[0].set_xlabel("Modulus size (bits)")
    axes[0].set_ylabel("Time (ms)")
    axes[0].set_title("Using RSA: polynomial in key size")
    axes[0].legend(); axes[0].grid(alpha=0.3)

    axes[1].semilogy([r[0] for r in fact], [r[1] for r in fact], "o-", color="#C44E52")
    axes[1].set_xlabel("Modulus size (bits)")
    axes[1].set_ylabel("Median time to factor (s, log scale)")
    axes[1].set_title("Breaking RSA with Pollard's rho: exponential")
    axes[1].grid(alpha=0.3, which="both")
    plt.tight_layout()
    plt.savefig(RESULTS / "rsa_timing.png", dpi=120)
    plt.close()

    lines = [
        "# Benchmark results",
        "",
        "Generated by `benchmarks/benchmark.py`. Pure Python; times are medians and vary by machine.",
        "",
        "## Using RSA",
        "",
        "| Modulus | Key generation (s) | Encrypt (ms) | Decrypt (ms) | Decrypt, CRT (ms) | CRT speed-up |",
        "|---|---|---|---|---|---|",
        *[f"| {b} | {kg:.3f} | {e * 1000:.3f} | {d * 1000:.2f} | {c * 1000:.2f} | {d / c:.1f}× |"
          for b, kg, e, d, c in costs],
        "",
        "## Breaking RSA (Pollard's rho, 5 keys per size)",
        "",
        "| Modulus | Median time to factor (s) |",
        "|---|---|",
        *[f"| {b} | {t:.4f} |" for b, t in fact],
        "",
        "![Timing](rsa_timing.png)",
    ]
    (RESULTS / "benchmark_results.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
